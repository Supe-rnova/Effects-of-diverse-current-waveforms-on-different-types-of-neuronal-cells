"""
Step 2a - download the three ModelDB models and compile their .mod files.

Run from the project root:
    python models/fetch_models.py            # download (if missing) + compile
    python models/fetch_models.py --force    # re-download and recompile

Models are taken from the official ModelDB mirror on GitHub
(github.com/ModelDBRepository/<accession>). Upstream files are copied
unchanged into models/<cell>/ next to our own GUI-free builder .hoc file.
"""
from __future__ import annotations

import argparse
import io
import shutil
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from models.mechanisms import compile_mechanisms  # noqa: E402

MODELS_DIR = ROOT / "models"

# folder name -> (ModelDB accession, reference, files that prove the download is complete)
SOURCES = {
    "stn": (74298, "Gillies A, Willshaw D (2006) J Neurophysiol 95:2352-2365",
            ["SThprotocell.hoc", "tools.hoc", "sth-data/tree0-nom.dat", "CaT.mod"]),
    "purkinje": (17664, "Miyasho T et al. (2001) Brain Res 891:106-115",
                 ["purkinje.hoc", "CaP2.mod"]),
    "ca1": (244688, "Migliore R et al. (2018) PLoS Comput Biol 14:e1006423",
            ["cell_seed3_0-pyr-08.hoc", "morphologies/mpg141209_A_idA.asc", "h.mod", "kmb.mod"]),
}

# Our own files that live in the same folders and must never be overwritten/deleted.
OUR_FILES = {"stn_build.hoc", "__init__.py"}


def download(accession: int, dest: Path) -> None:
    url = f"https://github.com/ModelDBRepository/{accession}/archive/refs/heads/master.zip"
    print(f"  downloading {url}")
    with urllib.request.urlopen(url, timeout=120) as r:
        data = r.read()
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        prefix = z.namelist()[0].split("/")[0] + "/"      # e.g. '74298-master/'
        for member in z.infolist():
            rel = member.filename[len(prefix):]
            if not rel or member.is_dir():
                continue
            target = dest / rel
            if target.name in OUR_FILES:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(z.read(member))


def marker(folder: Path, accession: int) -> Path:
    return folder / f".modeldb_{accession}"


def wipe_stale(folder: Path, accession: int) -> None:
    """If the folder holds files from a different model version, delete them
    (only files fetch_models.py itself downloaded - our own files are kept)."""
    if marker(folder, accession).exists() or not any(folder.iterdir()):
        return
    stale = [p for p in folder.iterdir() if p.name not in OUR_FILES]
    if not stale:
        return
    print(f"  removing {len(stale)} files from a previous model version in {folder.name}/")
    for p in stale:
        shutil.rmtree(p) if p.is_dir() else p.unlink()


def make_purkinje_nogui(folder: Path) -> None:
    """purkinje.hoc opens NEURON's GUI main menu; write a copy without those lines."""
    src = (folder / "purkinje.hoc").read_text(errors="replace").splitlines()
    keep = [ln for ln in src if "noload.hoc" not in ln and "nrnmainmenu" not in ln]
    header = ["// Auto-generated by fetch_models.py from purkinje.hoc (Miyasho et al. 2001):",
              "// identical except the two GUI lines (noload.hoc, nrnmainmenu) are removed.",
              'load_file("stdrun.hoc")']
    (folder / "purkinje_nogui.hoc").write_text("\n".join(header + keep) + "\n")


def clean_compiled(folder: Path) -> None:
    for p in [folder / "nrnmech.dll", *[folder / a for a in ("x86_64", "arm64", "aarch64")]]:
        if p.is_dir():
            shutil.rmtree(p)
        elif p.exists():
            p.unlink()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="re-download and recompile")
    args = ap.parse_args()

    for name, (acc, ref, must_exist) in SOURCES.items():
        folder = MODELS_DIR / name
        folder.mkdir(exist_ok=True)
        print(f"\n=== {name}  (ModelDB {acc}; {ref})")
        wipe_stale(folder, acc)
        complete = all((folder / f).exists() for f in must_exist)
        if args.force or not complete:
            download(acc, folder)
            missing = [f for f in must_exist if not (folder / f).exists()]
            if missing:
                raise RuntimeError(f"download of {acc} incomplete, missing {missing}")
            marker(folder, acc).write_text(ref + "\n")
        else:
            print("  already downloaded")
            marker(folder, acc).write_text(ref + "\n")

        if name == "purkinje":
            make_purkinje_nogui(folder)
        if args.force:
            clean_compiled(folder)
        compile_mechanisms(folder, force=args.force)

    print("\nAll models downloaded and compiled. Next: python models/test_models.py")


if __name__ == "__main__":
    main()
